export function convertS2HK(text: string): string {
  if (!text) return "";

  let result = text;

  // 1. 优先替换专有名词/地道词汇
  Object.keys(s2hkMap).forEach((sWord) => {
    if (result.includes(sWord)) {
      result = result.replaceAll(sWord, s2hkMap[sWord]);
    }
  });

  // 2. 单字简转繁 (常用字快速转换)
  let convertedChars = "";
  for (let i = 0; i < result.length; i++) {
    const char = result[i];
    const index = charS2HK.indexOf(char);
    if (index !== -1 && charT2HK[index]) {
      convertedChars += charT2HK[index];
    } else {
      convertedChars += char;
    }
  }

  return convertedChars;
}
